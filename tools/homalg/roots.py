"""Generate root modules, excluding auxiliary and cited leaves (§4.4)."""

from pathlib import Path

from homalg.repository import DOC_KEY, documents, node_paths

GENERATED = "-- Generated by homalg gen-roots. Do not edit.\n"


def generate_roots(repo: Path, selected: tuple[str, ...] = ()) -> dict[str, str]:
    """Return mirrored relative paths; the library root always includes all documents."""
    keys = documents(repo)
    documents(repo, selected)
    output = {}
    registered_roots = []
    for key in keys:
        paths = node_paths(repo, [key])
        if not paths:
            continue
        registered_roots.append(f"import HomAlg.{key}\n")
        if selected and key not in selected:
            continue
        imports = [
            f"import HomAlg.{key}.{path.stem}\n"
            for path in paths
            if not path.stem.startswith(("Aux_", "Cited_"))
        ]
        output[f"HomAlg/{key}.lean"] = GENERATED + "".join(imports)
    output["HomAlg.lean"] = GENERATED + "".join(registered_roots)
    return output


def stale_roots(repo: Path, selected: tuple[str, ...] = ()) -> list[str]:
    """Find document roots that no longer correspond to any registered node files."""
    expected = generate_roots(repo, selected)
    return [
        path.relative_to(repo).as_posix()
        for path in sorted((repo / "HomAlg").glob("*.lean"))
        if DOC_KEY.fullmatch(path.stem)
        and (not selected or path.stem in selected)
        and path.relative_to(repo).as_posix() not in expected
    ]
