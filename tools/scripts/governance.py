def render_codeowners(owner: str) -> str:
    """Render ordered ownership exceptions, including protected relation reviews."""
    lines = ["# Generated by tools/scripts/governance.py; see docs/CI.md.", f"* @{owner}"]
    lines.extend(UNOWNED)
    lines.extend(
        [
            f"/taxonomy/ @{owner}",
            "/taxonomy/tags.yaml",
            "/taxonomy/concepts.yaml",
            "/taxonomy/relations/",
            f"/taxonomy/relations/_reviews.yaml @{owner}",
        ]
    )
    return "\n".join(lines) + "\n"


def build_plan(
    repository: str,
    owner_kind: str = "user",
    owner_login: str | None = None,
    team_id: int | None = None,
    root: Path = ROOT,
) -> dict[str, Any]:
    """Return an offline, reviewable plan without accessing GitHub or changing files."""
    if not re.fullmatch(r"[A-Za-z0-9-]+/[A-Za-z0-9_.-]+", repository):
        raise ValueError("repository must be OWNER/REPOSITORY")
    account, _ = repository.split("/", 1)
    if owner_kind not in {"user", "org"}:
        raise ValueError("owner kind must be user or org")
    if owner_kind == "org" and (not owner_login or team_id is None or team_id <= 0):
        raise ValueError("org mode requires --owner-login and a positive --team-id")
    owner_login = owner_login or account
    if not re.fullmatch(r"[A-Za-z0-9-]+", owner_login):
        raise ValueError("owner login must be a GitHub user login")
    if owner_kind == "user" and owner_login.lower() != account.lower():
        raise ValueError("in user mode, owner login must equal the repository owner")
    code_owner = owner_login if owner_kind == "user" else f"{account}/homalg-maintainers"
    actor = {
        "actor_type": "RepositoryRole" if owner_kind == "user" else "Team",
        "actor_id": 5 if owner_kind == "user" else team_id,
        "bypass_mode": "pull_request",
    }
    rulesets = []
    for name in ("main", "status-branches"):
        data = json.loads((root / ".github" / "rulesets" / f"{name}.json").read_text())
        data["bypass_actors"] = [copy.deepcopy(actor)]
        rulesets.append(data)
    return {
        "repository": repository,
        "owner_kind": owner_kind,
        "codeowners": render_codeowners(code_owner),
        "rulesets": rulesets,
        "repository_settings": {
            "allow_auto_merge": True,
            "allow_squash_merge": True,
            "allow_merge_commit": False,
            "allow_rebase_merge": False,
            "delete_branch_on_merge": True,
        },
        "actions_permissions": {"default_workflow_permissions": "read"},
        "pages": {"build_type": "workflow"},
        "variable": {"name": "HOMALG_OWNER", "value": owner_login},
        "labels": [
            {"name": name, "color": color, "description": description}
            for name, (color, description) in LABELS.items()
        ],
    }


class GitHub:
    """Small JSON-only gh adapter with explicit methods and no shell interpolation."""

    def api(
        self,
        method: str,
        endpoint: str,
        payload: dict[str, Any] | None = None,
        *,
        missing_ok: bool = False,
        paginate: bool = False,
    ) -> Any:
        """Call the GitHub API, distinguishing missing resources from other failures."""
        command = ["gh", "api", "--method", method, endpoint]
        if payload is not None:
            command.extend(["--input", "-"])
        if paginate:
            command.extend(["--paginate", "--slurp"])
        result = subprocess.run(
            command,
            input=json.dumps(payload) if payload is not None else None,
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode:
            if missing_ok and "(HTTP 404)" in result.stderr:
                return None
            raise RuntimeError(f"gh api {method} {endpoint}: {result.stderr.strip()}")
        data = json.loads(result.stdout) if result.stdout.strip() else None
        if paginate:
            return [entry for page in data for entry in page]
        return data


def _contains(actual: Any, expected: Any) -> bool:
    """Compare requested fields while tolerating GitHub's extra response metadata."""
    if isinstance(expected, dict):
        return isinstance(actual, dict) and all(
            key in actual and _contains(actual[key], value) for key, value in expected.items()
        )
    if isinstance(expected, list):
        return (
            isinstance(actual, list)
            and len(actual) == len(expected)
            and all(any(_contains(item, target) for item in actual) for target in expected)
        )
    return actual == expected


def apply_plan(plan: dict[str, Any], github: GitHub) -> None:
    """Idempotently configure one existing repository and verify ruleset writes."""
    base = f"repos/{plan['repository']}"
    repository = github.api("GET", base)
    expected_kind = "User" if plan["owner_kind"] == "user" else "Organization"
    if repository["owner"]["type"] != expected_kind:
        raise ValueError("repository owner type differs from --owner-kind")
    if repository.get("archived"):
        raise ValueError("cannot configure an archived repository")
    if plan["owner_kind"] == "org":
        account = plan["repository"].split("/", 1)[0]
        team = github.api("GET", f"orgs/{account}/teams/homalg-maintainers")
        if team["id"] != plan["rulesets"][0]["bypass_actors"][0]["actor_id"]:
            raise ValueError("--team-id does not identify the homalg-maintainers team")
    existing = github.api("GET", f"{base}/rulesets", paginate=True)
    for ruleset in plan["rulesets"]:
        matches = [item for item in existing if item["name"] == ruleset["name"]]
        if len(matches) > 1:
            raise ValueError(f"multiple rulesets named {ruleset['name']}; resolve duplicates first")
        if matches:
            ruleset_id = matches[0]["id"]
            github.api("PUT", f"{base}/rulesets/{ruleset_id}", ruleset)
        else:
            result = github.api("POST", f"{base}/rulesets", ruleset)
            ruleset_id = result["id"]
        observed = github.api("GET", f"{base}/rulesets/{ruleset_id}")
        if not _contains(observed, ruleset):
            raise RuntimeError(f"ruleset read-back differs for {ruleset['name']}")
    github.api("PATCH", base, plan["repository_settings"])
    github.api("PUT", f"{base}/actions/permissions/workflow", plan["actions_permissions"])
    pages = github.api("GET", f"{base}/pages", missing_ok=True)
    github.api("POST" if pages is None else "PUT", f"{base}/pages", plan["pages"])
    variable = plan["variable"]
    endpoint = f"{base}/actions/variables/{variable['name']}"
    current = github.api("GET", endpoint, missing_ok=True)
    github.api(
        "POST" if current is None else "PATCH",
        f"{base}/actions/variables" if current is None else endpoint,
        variable,
    )
    existing_labels = github.api("GET", f"{base}/labels", paginate=True)
    names = {label["name"] for label in existing_labels}
    for label in plan["labels"]:
        exists = label["name"] in names
        endpoint = f"{base}/labels/{label['name']}" if exists else f"{base}/labels"
        github.api("PATCH" if exists else "POST", endpoint, label)


def write_codeowners(content: str, root: Path = ROOT) -> None:
    """Atomically render the only local file affected by governance setup."""
    destination = root / ".github" / "CODEOWNERS"
    destination.parent.mkdir(parents=True, exist_ok=True)
    path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=destination.parent, delete=False
        ) as temporary:
            path = Path(temporary.name)
            temporary.write(content)
        path.chmod(0o644)
        path.replace(destination)
    finally:
        if path is not None:
            path.unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    """Print the plan by default; mutate GitHub only with the explicit --apply flag."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", default=os.getenv("HOMALG_REPOSITORY"))
    parser.add_argument(
        "--owner-kind", choices=("user", "org"), default=os.getenv("GOVERNANCE_OWNER_KIND", "user")
    )
    parser.add_argument("--owner-login", help="human maintainer login; required in org mode")
    parser.add_argument("--team-id", type=int, help="homalg-maintainers team ID in org mode")
    parser.add_argument("--write-codeowners", action="store_true", help="render CODEOWNERS locally")
    parser.add_argument(
        "--apply", action="store_true", help="apply the plan to the existing repository"
    )
    args = parser.parse_args(argv)
    if not args.repository:
        parser.error("set HOMALG_REPOSITORY=OWNER/REPO or pass --repository OWNER/REPO")
    try:
        plan = build_plan(args.repository, args.owner_kind, args.owner_login, args.team_id)
        print(json.dumps(plan, sort_keys=True, indent=2))
        if args.write_codeowners:
            write_codeowners(plan["codeowners"])
        if args.apply:
            if (ROOT / ".github" / "CODEOWNERS").read_text() != plan["codeowners"]:
                raise ValueError(
                    "render and commit CODEOWNERS with --write-codeowners before --apply"
                )
            apply_plan(plan, GitHub())
            if args.owner_kind == "user":
                print(
                    "code-owner review is satisfied only through bypass; "
                    "add a second maintainer to make it meaningful",
                    file=sys.stderr,
                )
            print(
                "Applied governance settings. Commit and push rendered CODEOWNERS.", file=sys.stderr
            )
    except ValueError as error:
        print(f"Configuration error: {error}", file=sys.stderr)
        return 2
    except (OSError, RuntimeError) as error:
        print(f"Governance failed: {error}", file=sys.stderr)
        return 3
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
