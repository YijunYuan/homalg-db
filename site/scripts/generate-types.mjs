/** Generate the TypeScript view of the versioned JSON contracts, without network I/O. */
import { readFile, readdir, writeFile, rename } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../..",
);
const schemaDir = path.join(root, "schema");
const output = path.join(root, "site/src/data/types.ts");
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check")) {
  throw new Error("Usage: node scripts/generate-types.mjs [--check]");
}

const pascalCase = (name) =>
  name
    .split(/[-.]/)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join("");
const files = (await readdir(schemaDir, { recursive: true }))
  .filter(
    (name) =>
      name.endsWith(".schema.json") && !name.endsWith(".strict.schema.json"),
  )
  .sort();
const schemas = new Map();
for (const file of files) {
  const schema = JSON.parse(await readFile(path.join(schemaDir, file), "utf8"));
  const name = file.startsWith("site/")
    ? `Site${pascalCase(path.basename(file, ".schema.json"))}`
    : pascalCase(file.slice(0, -12));
  schemas.set(schema.$id, { schema, name });
}

/** Rewrite every external reference into a single in-memory schema graph. */
function localize(value, base) {
  if (Array.isArray(value)) return value.map((item) => localize(item, base));
  if (value === null || typeof value !== "object") return value;
  const result = {};
  for (const [key, item] of Object.entries(value)) {
    if (["$id", "$schema", "if", "then", "else"].includes(key)) continue;
    if (key === "$ref") {
      const target = new URL(item, base);
      const fragment = target.hash;
      target.hash = "";
      const entry = schemas.get(target.href);
      if (!entry)
        throw new Error(`Unknown local schema reference: ${target.href}`);
      result.$ref = `#/$defs/${entry.name}${fragment.slice(1)}`;
    } else {
      result[key] = localize(item, base);
    }
  }
  // Conditional validation remains in Python; empty conditional intersections
  // confuse the type generator and erase otherwise declared object properties.
  if (result.allOf) {
    result.allOf = result.allOf.filter((item) => Object.keys(item).length > 0);
    if (!result.allOf.length) delete result.allOf;
  }
  // json-schema-to-typescript uses the draft-07 tuple spelling for TypeScript output.
  // Runtime validation continues to use the unmodified draft 2020-12 schemas.
  if (result.prefixItems) {
    result.additionalItems = result.items ?? true;
    result.items = result.prefixItems;
    delete result.prefixItems;
  }
  return result;
}

const definitions = {};
const properties = {};
for (const [id, { schema, name }] of schemas) {
  definitions[name] = { ...localize(schema, id), title: name };
  if (schema.type || schema.$ref || schema.allOf)
    properties[name] = { $ref: `#/$defs/${name}` };
  for (const definition of Object.keys(schema.$defs ?? {})) {
    const key =
      name === "Common" || name === "SiteCommon"
        ? definition
        : `${name}${definition}`;
    properties[key] = { $ref: `#/$defs/${name}/$defs/${definition}` };
  }
}
const generated = await compile(
  {
    title: "HomalgSchemaTypes",
    type: "object",
    properties,
    additionalProperties: false,
    $defs: definitions,
  },
  "HomalgSchemaTypes",
  {
    bannerComment:
      "/* Generated by npm run generate-types from the JSON schemas in schema/. Do not edit. */\n/* Runtime validation uses JSON Schema; these types are a development aid. */",
    additionalProperties: true,
    style: {
      printWidth: 100,
      singleQuote: false,
      semi: true,
      trailingComma: "none",
    },
    $refOptions: { resolve: { http: false, file: false } },
  },
);
if (check) {
  const current = await readFile(output, "utf8").catch(() => "");
  if (current !== generated)
    throw new Error("Generated types are stale. Run npm run generate-types.");
  console.log("Generated schema types are current.");
} else {
  const temporary = `${output}.${process.pid}.tmp`;
  await writeFile(temporary, generated);
  await rename(temporary, output);
  console.log(
    `Generated ${path.relative(root, output)} from ${files.length} schemas.`,
  );
}
